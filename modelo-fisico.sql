CREATE SCHEMA IF NOT EXISTS proveedores;
CREATE SCHEMA IF NOT EXISTS catalogo;
CREATE SCHEMA IF NOT EXISTS ordenes;
CREATE SCHEMA IF NOT EXISTS logistica;
CREATE SCHEMA IF NOT EXISTS auditoria;

-- =============================================================================
-- 2. ESQUEMA: PROVEEDORES
-- =============================================================================

CREATE TABLE proveedores.proveedor (
    proveedor_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nit             VARCHAR(20) NOT NULL,
    nombre          VARCHAR(150) NOT NULL,
    estado          VARCHAR(20) NOT NULL,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_proveedor PRIMARY KEY (proveedor_id),
    CONSTRAINT uq_proveedor_nit UNIQUE (nit),
    CONSTRAINT chk_proveedor_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO'))
);

COMMENT ON TABLE proveedores.proveedor IS
'Entidad principal de proveedores (100k registros). Soporta distribucion Zipf y base para Q1.';

COMMENT ON COLUMN proveedores.proveedor.proveedor_id IS
'Generado BY DEFAULT para permitir IDs explicitos desde el generador determinista y secuencias automaticas en la aplicacion.';

CREATE TABLE proveedores.contrato_suministro (
    contrato_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proveedor_id    BIGINT NOT NULL,
    numero_contrato VARCHAR(50) NOT NULL,
    fecha_inicio    TIMESTAMPTZ NOT NULL,
    fecha_fin       TIMESTAMPTZ NOT NULL,
    estado          VARCHAR(20) NOT NULL,

    CONSTRAINT pk_contrato_suministro PRIMARY KEY (contrato_id),
    CONSTRAINT fk_contrato_proveedor
        FOREIGN KEY (proveedor_id)
        REFERENCES proveedores.proveedor (proveedor_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_contrato_numero UNIQUE (numero_contrato),
    CONSTRAINT chk_contrato_fechas
        CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT chk_contrato_estado
        CHECK (estado IN ('VIGENTE', 'VENCIDO', 'TERMINADO'))
);

COMMENT ON TABLE proveedores.contrato_suministro IS
'Contratos comerciales (~10k-15k registros). Soporta validacion en Q1 y casos borde de horario exacto.';

COMMENT ON COLUMN proveedores.contrato_suministro.fecha_fin IS
'TIMESTAMPTZ indispensable para validar con precision el caso borde de vencimiento al mediodia.';

-- =============================================================================
-- 3. ESQUEMA: CATALOGO
-- =============================================================================

CREATE TABLE catalogo.sku (
    sku_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo_sku      VARCHAR(50) NOT NULL,
    nombre          VARCHAR(200) NOT NULL,
    categoria       VARCHAR(100) NOT NULL,
    unidad_medida   VARCHAR(20) NOT NULL,

    CONSTRAINT pk_sku PRIMARY KEY (sku_id),
    CONSTRAINT uq_sku_codigo UNIQUE (codigo_sku)
);

COMMENT ON TABLE catalogo.sku IS
'Maestro de productos (200k-400k registros). La categoria se duplica intencionalmente en linea_orden como snapshot.';

CREATE TABLE catalogo.catalogo_negociado (
    catalogo_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sku_id          BIGINT NOT NULL,
    proveedor_id    BIGINT NOT NULL,
    precio          NUMERIC(12,2) NOT NULL,
    fecha_inicio    TIMESTAMPTZ NOT NULL,
    fecha_fin       TIMESTAMPTZ NOT NULL,
    estado          VARCHAR(20) NOT NULL,

    CONSTRAINT pk_catalogo_negociado PRIMARY KEY (catalogo_id),
    CONSTRAINT fk_catalogo_sku
        FOREIGN KEY (sku_id)
        REFERENCES catalogo.sku (sku_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_catalogo_precio
        CHECK (precio > 0),
    CONSTRAINT chk_catalogo_fechas
        CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT chk_catalogo_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

COMMENT ON TABLE catalogo.catalogo_negociado IS
'Relacion comercial proveedor-SKU-precio. Su cardinalidad se desacopla del maestro SKU para reflejar negociaciones reales y sesgo del 10% de SKUs en 60% de las lineas.';

-- =============================================================================
-- 4. ESQUEMA: ORDENES
-- =============================================================================

CREATE TABLE ordenes.orden_compra (
    orden_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proveedor_id             BIGINT NOT NULL,
    cedi_id                  BIGINT NOT NULL,
    fecha_creacion           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_entrega_solicitada TIMESTAMPTZ NOT NULL,
    fecha_recepcion          TIMESTAMPTZ NULL,
    estado                   VARCHAR(30) NOT NULL,
    total                    NUMERIC(14,2) NOT NULL,

    CONSTRAINT pk_orden_compra PRIMARY KEY (orden_id),
    CONSTRAINT chk_orden_total
        CHECK (total >= 0),
    CONSTRAINT chk_orden_estadoor
        CHECK (
            estado IN (
                'PENDIENTE',
                'EN_VALIDACION',
                'CONFIRMADA',
                'RECHAZADA',
                'CANCELADA'
            )
        )
);

COMMENT ON TABLE ordenes.orden_compra IS
'Cabecera de ordenes (300k-500k registros). Referencias externas estrictamente logicas.';

CREATE TABLE ordenes.linea_orden (
    linea_orden_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    orden_id            BIGINT NOT NULL,
    sku_id              BIGINT NOT NULL,
    categoria           VARCHAR(100) NOT NULL,
    cantidad_solicitada INTEGER NOT NULL,
    cantidad_recibida   INTEGER NOT NULL DEFAULT 0,
    precio_unitario     NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_linea_orden PRIMARY KEY (linea_orden_id),
    CONSTRAINT fk_linea_orden_cabecera
        FOREIGN KEY (orden_id)
        REFERENCES ordenes.orden_compra (orden_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_linea_cantidades
        CHECK (
            cantidad_solicitada > 0
            AND cantidad_recibida >= 0
            AND cantidad_recibida <= cantidad_solicitada
        ),
    CONSTRAINT chk_linea_precio
        CHECK (precio_unitario >= 0)
);

COMMENT ON TABLE ordenes.linea_orden IS
'Detalle de lineas (1.5M-3M filas). Incluye restriccion que delimita el Fill Rate entre 0% y 100%.';

CREATE TABLE ordenes.confirmacion_orden (
    confirmacion_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    orden_id            BIGINT NOT NULL,
    idempotency_key     VARCHAR(100) NOT NULL,
    estado              VARCHAR(30) NOT NULL,
    fecha_solicitud     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_confirmacion  TIMESTAMPTZ NULL,
    motivo_rechazo      VARCHAR(255) NULL,

    CONSTRAINT pk_confirmacion_orden PRIMARY KEY (confirmacion_id),
    CONSTRAINT fk_confirmacion_orden
        FOREIGN KEY (orden_id)
        REFERENCES ordenes.orden_compra (orden_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_confirmacion_orden
        UNIQUE (orden_id),
    CONSTRAINT uq_confirmacion_idempotency
        UNIQUE (idempotency_key),
    CONSTRAINT chk_confirmacion_estado
        CHECK (
            estado IN (
                'PROCESSING',
                'SUCCEEDED',
                'FAILED'
            )
        )
);

COMMENT ON TABLE ordenes.confirmacion_orden IS
'Separa la operacion de confirmacion garantizando idempotencia estricta por idempotency_key.';

CREATE TABLE ordenes.outbox_evento (
    outbox_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    aggregate_id      BIGINT NOT NULL,
    tipo_evento       VARCHAR(50) NOT NULL,
    payload           JSONB NOT NULL,
    fecha_creacion    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    publicado         BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_publicacion TIMESTAMPTZ NULL,

    CONSTRAINT pk_outbox_evento PRIMARY KEY (outbox_id)
);

COMMENT ON TABLE ordenes.outbox_evento IS
'Garantiza la publicacion de eventos como OrdenConfirmada de forma atomica tras el commit transaccional.';

-- =============================================================================
-- 5. ESQUEMA: LOGISTICA
-- =============================================================================

CREATE TABLE logistica.cedi (
    cedi_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100) NOT NULL,
    capacidad   INTEGER NOT NULL,
    estado      VARCHAR(20) NOT NULL,

    CONSTRAINT pk_cedi PRIMARY KEY (cedi_id),
    CONSTRAINT chk_cedi_capacidad
        CHECK (capacidad > 0),
    CONSTRAINT chk_cedi_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

COMMENT ON TABLE logistica.cedi IS
'Centros de distribucion (5 registros fijos).';

CREATE TABLE logistica.franja_descargue (
    franja_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cedi_id           BIGINT NOT NULL,
    fecha             DATE NOT NULL,
    hora_inicio       TIME NOT NULL,
    hora_fin          TIME NOT NULL,
    capacidad         INTEGER NOT NULL,
    reservas_actuales INTEGER NOT NULL DEFAULT 0,
    estado            VARCHAR(20) NOT NULL,

    CONSTRAINT pk_franja_descargue PRIMARY KEY (franja_id),
    CONSTRAINT fk_franja_cedi
        FOREIGN KEY (cedi_id)
        REFERENCES logistica.cedi (cedi_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_franja_horas
        CHECK (hora_fin > hora_inicio),
    CONSTRAINT chk_franja_capacidad
        CHECK (
            capacidad > 0
            AND reservas_actuales >= 0
            AND reservas_actuales <= capacidad
        ),
    CONSTRAINT chk_franja_estado
        CHECK (
            estado IN (
                'DISPONIBLE',
                'COMPLETA',
                'BLOQUEADA'
            )
        )
);

COMMENT ON TABLE logistica.franja_descargue IS
'Franjas de descargue por CEDI (90k-150k registros). Recurso escaso de alta concurrencia.';

CREATE TABLE logistica.reserva_franja (
    reserva_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    franja_id        BIGINT NOT NULL,
    orden_id         BIGINT NOT NULL,
    estado           VARCHAR(20) NOT NULL,
    fecha_reserva    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion TIMESTAMPTZ NULL,

    CONSTRAINT pk_reserva_franja PRIMARY KEY (reserva_id),
    CONSTRAINT fk_reserva_franja
        FOREIGN KEY (franja_id)
        REFERENCES logistica.franja_descargue (franja_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_reserva_estado
        CHECK (
            estado IN (
                'CONFIRMADA',
                'PENDIENTE',
                'CANCELADA'
            )
        )
);

COMMENT ON TABLE logistica.reserva_franja IS
'Historico de reservas. El indice unico parcial evita reservas activas duplicadas y permite conservar historial de cancelaciones.';

-- =============================================================================
-- 6. CAPACIDAD TRANSVERSAL: AUDITORIA
--    Particionada mensualmente durante 24 meses
-- =============================================================================

CREATE TABLE auditoria.evento_auditoria (
    evento_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    modulo          VARCHAR(50) NOT NULL,
    entidad         VARCHAR(50) NOT NULL,
    entidad_id      VARCHAR(100) NOT NULL,
    tipo_evento     VARCHAR(50) NOT NULL,
    estado_anterior VARCHAR(30) NULL,
    estado_nuevo    VARCHAR(30) NULL,
    fecha_evento    TIMESTAMPTZ NOT NULL,
    detalle         JSONB NULL,

    CONSTRAINT pk_evento_auditoria
        PRIMARY KEY (evento_id, fecha_evento)
) PARTITION BY RANGE (fecha_evento);

COMMENT ON TABLE auditoria.evento_auditoria IS
'Tabla transversal de auditoria (500k-800k eventos). Particionada explicitamente en 24 meses.';

